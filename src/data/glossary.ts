/** 名言の本文に現れた語だけを、長いものから順に返す */
export function findTerms(text: string, limit = 5): Term[] {
  return glossary
    .filter((t) => text.includes(t.word))
    .sort((a, b) => b.word.length - a.word.length)
    .slice(0, limit);
}
